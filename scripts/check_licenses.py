#!/usr/bin/env python3
"""Dependency licence inventory (offline: reads installed metadata, nothing is sent anywhere).

    cd backend && uv run python ../scripts/check_licenses.py > ../docs/LICENSES.md

Python: every distribution installed in the backend venv (importlib.metadata).
JavaScript: production dependencies of the dashboard and their transitive deps (package-lock.json),
which are the packages shipped in the built bundle. Dev-only tooling is listed separately by count.
Exit code 1 if a shipped package has a licence outside ALLOWED (copyleft or unknown) — review it.
"""

from __future__ import annotations

import json
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ALLOWED = {
    "MIT", "MIT-0", "ISC", "BSD", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "Apache 2.0", "Apache Software License",
    "Python-2.0", "PSF-2.0", "Python Software Foundation License", "OFL-1.1", "0BSD", "Unlicense", "CC0-1.0",
    "BlueOak-1.0.0", "MPL-2.0", "Mozilla Public License 2.0 (MPL 2.0)", "EPL-2.0", "Zlib", "CC-BY-4.0",
    # trove classifier spellings (after " License" is stripped)
    "Apache Software", "Python Software Foundation", "Mozilla Public 2.0 (MPL 2.0)", "ISC (ISCL)",
}


def _py_license(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expr = meta.get("License-Expression")
    if expr:
        return expr.strip()
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    classifiers = [c.replace(" License", "").replace("MIT", "MIT") for c in classifiers if c != "OSI Approved"]
    if classifiers:
        return " / ".join(sorted(set(classifiers)))
    raw = (meta.get("License") or "").strip().splitlines()
    return raw[0][:60] if raw else "UNKNOWN"


def _ok(lic: str) -> bool:
    parts = [p.strip(" ()") for p in lic.replace(" OR ", "/").replace(" AND ", "/").replace(" or ", "/").split("/")]
    return any(p in ALLOWED or p.replace(" License", "") in ALLOWED for p in parts)


def python_rows() -> list[tuple[str, str, str]]:
    rows = {}
    for dist in metadata.distributions():
        name = dist.metadata.get("Name") or "?"
        if name.startswith("ci-") or name == "codebase-intelligence":
            continue
        rows[name.lower()] = (name, dist.version, _py_license(dist))
    return sorted(rows.values(), key=lambda r: r[0].lower())


def js_rows() -> tuple[list[tuple[str, str, str]], int]:
    lock = json.loads((ROOT / "frontend" / "package-lock.json").read_text())
    pkgs = lock.get("packages", {})
    shipped, dev = [], 0
    for path, info in pkgs.items():
        if not path.startswith("node_modules/"):
            continue
        if info.get("dev"):
            dev += 1
            continue
        name = path.split("node_modules/")[-1]
        lic = info.get("license")
        if not lic:
            pj = ROOT / "frontend" / path / "package.json"
            if pj.exists():
                lic = json.loads(pj.read_text()).get("license")
        shipped.append((name, info.get("version", "?"), str(lic or "UNKNOWN")))
    return sorted(shipped), dev


def main() -> int:
    py = python_rows()
    js, dev_count = js_rows()
    flagged = [r for r in js if not _ok(r[2])]
    py_flagged = [r for r in py if not _ok(r[2])]
    out = [
        "# Dependency licences",
        "",
        "Generated by `scripts/check_licenses.py` from installed metadata (offline). Regenerate after dependency changes:",
        "",
        "```bash",
        "cd backend && uv run python ../scripts/check_licenses.py > ../docs/LICENSES.md",
        "```",
        "",
        f"- Dashboard: **{len(js)}** packages shipped in the bundle; {dev_count} dev-only packages (build, test, lint) not shipped.",
        f"- Backend: **{len(py)}** Python distributions in the venv (runtime + dev tools).",
        f"- Needs review (copyleft, unknown or non-standard licence text): **{len(flagged)}** shipped JS, **{len(py_flagged)}** Python.",
        "",
    ]
    if flagged or py_flagged:
        out += ["## Needs review", "", "| Package | Version | Licence |", "|---|---|---|"]
        out += [f"| {n} (npm) | {v} | {lic} |" for n, v, lic in flagged]
        out += [f"| {n} (PyPI) | {v} | {lic} |" for n, v, lic in py_flagged]
        out += ["", "Unknown usually means the licence is only in the package's LICENSE file, not its metadata.", ""]
    out += ["## Dashboard (shipped npm packages)", "", "| Package | Version | Licence |", "|---|---|---|"]
    out += [f"| {n} | {v} | {lic} |" for n, v, lic in js]
    out += ["", "## Backend (Python)", "", "| Package | Version | Licence |", "|---|---|---|"]
    out += [f"| {n} | {v} | {lic} |" for n, v, lic in py]
    print("\n".join(out))
    return 1 if flagged else 0


if __name__ == "__main__":
    sys.exit(main())
