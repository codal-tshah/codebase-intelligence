/**
 * Client-side export of the *current view* (what is on the canvas): Mermaid, Markdown, JSON, SVG
 * and PNG. Nothing leaves the browser. SVG is drawn from our own layout (node positions/sizes and
 * edge endpoints), so it is complete even for parts of the graph outside the viewport.
 */
import type { Edge, Node } from "@xyflow/react";
import { EDGE_STYLE } from "../graphTheme";
import type { ArchNodeData } from "../flow";
import type { GraphPayload } from "../types";

// ------------------------------------------------------------------ text formats

function mermaidLabel(text: string): string {
  // Quoted Mermaid labels: escape quotes and angle brackets; drop backticks (markdown strings).
  return text.replace(/`/g, "").replace(/"/g, "#quot;").replace(/</g, "#lt;").replace(/>/g, "#gt;").replace(/\n/g, " ");
}

/** Mermaid flowchart of the view. Ids are re-numbered (n0, n1, …) so any node id is safe. */
export function toMermaid(payload: GraphPayload, title?: string): string {
  const ids = new Map(payload.nodes.map((n, i) => [n.id, `n${i}`]));
  const lines = ["flowchart LR"];
  if (title) lines.unshift(`%% ${title.replace(/\n/g, " ")}`);
  for (const n of payload.nodes) {
    const shape = n.node_type === "Model" || n.node_type === "Table" ? ["[(", ")]"] : ["[", "]"];
    lines.push(`  ${ids.get(n.id)}${shape[0]}"${mermaidLabel(n.label)}<br/><small>${mermaidLabel(n.node_type)}</small>"${shape[1]}`);
  }
  for (const e of payload.edges) {
    const a = ids.get(e.source);
    const b = ids.get(e.target);
    if (!a || !b) continue;
    const style = EDGE_STYLE[e.edge_type];
    const dashed = style?.dashed || (e.confidence ?? 1) < 0.7;
    const label = mermaidLabel(style?.label ?? e.edge_type).replace(/\|/g, "/");
    lines.push(`  ${a} ${dashed ? "-.->" : "-->"}|${label}| ${b}`);
  }
  return lines.join("\n") + "\n";
}

function mdCell(text: string | null | undefined): string {
  return (text ?? "").replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\n/g, " ");
}

/** Markdown report: a Mermaid diagram plus node and edge tables (paste into a PR or wiki). */
export function toMarkdown(payload: GraphPayload, meta: { project: string; view: string }): string {
  const names = new Map(payload.nodes.map((n) => [n.id, n.label]));
  const out = [
    `# ${mdCell(meta.project)} — ${mdCell(meta.view)}`,
    "",
    `${payload.nodes.length} nodes, ${payload.edges.length} edges. Generated by Codebase Intelligence from static analysis.`,
    "",
    "```mermaid",
    toMermaid(payload).trimEnd(),
    "```",
    "",
    "## Nodes",
    "",
    "| Name | Type | Layer | Source |",
    "|---|---|---|---|",
    ...payload.nodes.map((n) => `| ${mdCell(n.label)} | ${mdCell(n.node_type)} | ${mdCell(n.layer)} | ${n.source_path ? `\`${mdCell(n.source_path)}\`` : ""} |`),
    "",
    "## Relations",
    "",
    "| From | Relation | To | Confidence |",
    "|---|---|---|---|",
    ...payload.edges.map(
      (e) =>
        `| ${mdCell(names.get(e.source) ?? e.source)} | ${mdCell(EDGE_STYLE[e.edge_type]?.label ?? e.edge_type)} | ${mdCell(names.get(e.target) ?? e.target)} | ${Math.round((e.confidence ?? 1) * 100)}% |`,
    ),
    "",
  ];
  return out.join("\n");
}

export function toJson(payload: GraphPayload, meta: { project: string; view: string }): string {
  return JSON.stringify({ version: 1, project: meta.project, view: meta.view, nodes: payload.nodes, edges: payload.edges }, null, 2);
}

// ------------------------------------------------------------------ SVG / PNG

function xml(text: string): string {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");
}

function clip(text: string, max: number): string {
  return text.length > max ? `${text.slice(0, max - 1)}…` : text;
}

type Box = { x: number; y: number; w: number; h: number };

/** Absolute boxes for React Flow nodes (children are positioned relative to their parent). */
export function absoluteBoxes(nodes: Node<ArchNodeData>[]): Map<string, Box> {
  const byId = new Map(nodes.map((n) => [n.id, n]));
  const out = new Map<string, Box>();
  const abs = (n: Node<ArchNodeData>, guard = 0): { x: number; y: number } => {
    const parent = n.parentId ? byId.get(n.parentId) : undefined;
    if (!parent || guard > 64) return { x: n.position.x, y: n.position.y };
    const p = abs(parent, guard + 1);
    return { x: p.x + n.position.x, y: p.y + n.position.y };
  };
  for (const n of nodes) {
    const { x, y } = abs(n);
    out.set(n.id, { x, y, w: Number(n.width ?? n.measured?.width ?? 216), h: Number(n.height ?? n.measured?.height ?? 78) });
  }
  return out;
}

function tint(hex: string, amount: number): string {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex);
  if (!m) return "#fcfbf8";
  const v = parseInt(m[1], 16);
  const base = [0xfc, 0xfb, 0xf8];
  const c = [(v >> 16) & 255, (v >> 8) & 255, v & 255].map((ch, i) => Math.round(ch * amount + base[i] * (1 - amount)));
  return `#${c.map((ch) => ch.toString(16).padStart(2, "0")).join("")}`;
}

/** Standalone SVG of the laid-out canvas (light theme, fonts with system fallbacks). */
export function toSvg(nodes: Node<ArchNodeData>[], edges: Edge[]): string {
  const boxes = absoluteBoxes(nodes.filter((n) => n.type !== "lane"));
  if (!boxes.size) return `<svg xmlns="http://www.w3.org/2000/svg" width="1" height="1"/>`;
  const pad = 32;
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const b of boxes.values()) {
    minX = Math.min(minX, b.x);
    minY = Math.min(minY, b.y);
    maxX = Math.max(maxX, b.x + b.w);
    maxY = Math.max(maxY, b.y + b.h);
  }
  const W = Math.ceil(maxX - minX + pad * 2);
  const H = Math.ceil(maxY - minY + pad * 2);
  const ox = pad - minX;
  const oy = pad - minY;
  const parts: string[] = [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" font-family="'Schibsted Grotesk', system-ui, sans-serif">`,
    `<rect width="100%" height="100%" fill="#f7f6f2"/>`,
    `<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="context-stroke"/></marker></defs>`,
  ];
  // groups first (they sit behind their children), then leaves
  const ordered = [...nodes].filter((n) => boxes.has(n.id)).sort((a, b) => Number(Boolean(b.data.exploreGroup)) - Number(Boolean(a.data.exploreGroup)));
  for (const n of ordered) {
    const b = boxes.get(n.id)!;
    const x = b.x + ox;
    const y = b.y + oy;
    const color = n.data.color || "#8a867c";
    const group = Boolean(n.data.exploreGroup);
    const dashed = n.data.inferred ? ` stroke-dasharray="5 4"` : "";
    parts.push(
      `<g><rect x="${x}" y="${y}" width="${b.w}" height="${b.h}" rx="8" fill="${group ? tint(color, 0.04) : tint(color, 0.07)}" stroke="${tint(color, 0.45)}"${dashed}/>`,
      `<rect x="${x}" y="${y + 10}" width="3" height="${Math.max(0, Math.min(b.h, 78) - 20)}" fill="${xml(color)}"/>`,
      `<text x="${x + 14}" y="${y + 22}" font-size="11" fill="#6b675d">${xml(clip(n.data.nodeType ?? "", 24))}</text>`,
      `<text x="${x + 14}" y="${y + 42}" font-size="13" font-weight="600" fill="#1d1c19">${xml(clip(String(n.data.label ?? n.id), group ? 48 : 28))}</text>`,
    );
    if (!group && n.data.path) {
      parts.push(`<text x="${x + 14}" y="${y + 60}" font-size="10.5" font-family="'IBM Plex Mono', ui-monospace, monospace" fill="#6b675d">${xml(clip(n.data.path, 32))}</text>`);
    }
    parts.push("</g>");
  }
  for (const e of edges) {
    const s = boxes.get(e.source);
    const t = boxes.get(e.target);
    if (!s || !t) continue;
    const x1 = s.x + s.w + ox;
    const y1 = s.y + Math.min(s.h, 78) / 2 + oy;
    const x2 = t.x + ox;
    const y2 = t.y + Math.min(t.h, 78) / 2 + oy;
    const dx = Math.max(40, Math.abs(x2 - x1) / 2);
    const st = (e.style ?? {}) as { stroke?: string; strokeDasharray?: string; opacity?: number };
    const dash = st.strokeDasharray ? ` stroke-dasharray="${xml(String(st.strokeDasharray))}"` : "";
    parts.push(
      `<path d="M${x1},${y1} C${x1 + dx},${y1} ${x2 - dx},${y2} ${x2},${y2}" fill="none" stroke="${xml(String(st.stroke ?? "#9a958a"))}" stroke-width="1.3"${dash} marker-end="url(#arrow)"/>`,
    );
  }
  parts.push("</svg>");
  return parts.join("\n");
}

/** Rasterise an SVG string to PNG in the browser (2× for crisp text). */
export async function svgToPng(svg: string, scale = 2): Promise<Blob> {
  const url = URL.createObjectURL(new Blob([svg], { type: "image/svg+xml" }));
  try {
    const img = new Image();
    await new Promise<void>((resolve, reject) => {
      img.onload = () => resolve();
      img.onerror = () => reject(new Error("could not render SVG"));
      img.src = url;
    });
    // Browsers cap canvas size (~16k px per side); scale down for very large graphs.
    const maxSide = 16000;
    const s = Math.min(scale, maxSide / Math.max(img.width, 1), maxSide / Math.max(img.height, 1));
    const canvas = document.createElement("canvas");
    canvas.width = Math.max(1, Math.round(img.width * s));
    canvas.height = Math.max(1, Math.round(img.height * s));
    const ctx = canvas.getContext("2d");
    if (!ctx) throw new Error("canvas unavailable");
    ctx.scale(s, s);
    ctx.drawImage(img, 0, 0);
    return await new Promise<Blob>((resolve, reject) =>
      canvas.toBlob((b) => (b ? resolve(b) : reject(new Error("PNG encoding failed"))), "image/png"),
    );
  } finally {
    URL.revokeObjectURL(url);
  }
}

export function safeFilename(...parts: string[]): string {
  return parts
    .join("-")
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 80) || "graph";
}
